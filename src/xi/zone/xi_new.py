"""``xi zone new`` — stamp out a fresh zone from a template bundle.

Copies the template's four DATs (zone, event, dialog, npc) into
FFXI_DIR/ROM10/2/ and registers them in FTABLE10 with the next free
zone ID (400+).  Templates are hand-curated zones packaged with
``xi zone make-template`` and stored in xi-tools-workspaces/templates/<id>/.

Spawn position is configured server-side (zone_settings); this command only
writes the client DATs.
"""

