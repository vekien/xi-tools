# ---------------------------------------------------------------------------
# Reverse lookup — identify a gear model's race/slot/model_id from just a DAT
# path or file_id. The RACE_TABLES above map (race, slot, model_id) -> file_id;
# we invert them so a bare DAT path is enough to detect the race (which makes
# race/slot/model_id optional on the gear commands).
# ---------------------------------------------------------------------------

# Matches a DAT reference with an explicit ROM token: 'rom/33/17',
# 'ROM/33/17.DAT', 'ROM10/200/3.DAT', or a full on-disk path ending in one.
_DAT_RE = re.compile(r'(?:^|/)rom(\d*)/(\d+)/(\d+)(?:\.dat)?$', re.IGNORECASE)
# Matches a bare 'subdir/file' with no ROM token (assumed base ROM).
_BARE_DAT_RE = re.compile(r'^(\d+)/(\d+)(?:\.dat)?$', re.IGNORECASE)


def match_race(name) -> str | None:
    """Return the canonical RACE_TABLES key for a case-insensitive race name,
    or None if ``name`` is not a known race."""
    if name is None:
        return None
    low = str(name).lower()
    for key in RACE_TABLES:
        if key.lower() == low:
            return key
    return None


def normalize_dat(spec) -> str | None:
    """Normalise a DAT reference to the canonical ``ROM/<sub>/<file>.DAT`` form
    emitted by ``ftable.xi_core.resolve_dat`` (so the two can be compared).

    Accepts ``rom/33/17``, ``ROM/33/17.DAT``, a full on-disk path, backslashes,
    or a bare ``33/17``. Returns None if it is not DAT-path-like.
    """
    s = str(spec).strip().strip('"').strip("'").replace('\\', '/')
    m = _DAT_RE.search(s)
    if m:
        idx, sub, fil = m.group(1), m.group(2), m.group(3)
        prefix = 'ROM' if idx in ('', '1') else f'ROM{idx}'
        return f'{prefix}/{sub}/{fil}.DAT'
    m = _BARE_DAT_RE.match(s)
    if m:
        return f'ROM/{m.group(1)}/{m.group(2)}.DAT'
    return None


def build_gear_index() -> dict:
    """Invert RACE_TABLES into ``{file_id: (race, slot, model_id)}`` across every
    race and slot. file_ids are unique per (race, slot, model_id)."""
    index = {}
    for race, raw in RACE_TABLES.items():
        race_table = parse_race_table(raw)
        for slot in SLOTS:
            for model_id, file_id in slot_file_ids(race_table[slot]):
                index[file_id] = (race, slot, model_id)
    return index


def detect_gear(spec, tables=None) -> tuple:
    """Identify the gear model referenced by ``spec`` and return
    ``(race, slot, model_id, file_id)``.

    ``spec`` may be a file_id (int or digit-string) or a DAT path
    (``rom/33/17``, ``ROM/33/17.DAT``, a full path, ...). Raises ValueError if
    ``spec`` is not a recognisable DAT/file_id, or maps to no registered gear
    model (e.g. it is a monster, zone, or UI DAT).
    """
    index = build_gear_index()

    # file_id form — direct table inversion, no FTABLE needed.
    if isinstance(spec, int) or (isinstance(spec, str) and spec.strip().isdigit()):
        file_id = int(spec)
        hit = index.get(file_id)
        if hit is None:
            raise ValueError(f"file_id {file_id} is not a registered gear model")
        return (*hit, file_id)

    # DAT-path form — resolve every gear file_id through the FTABLE and find the
    # one that lands on this DAT. Restricting to gear file_ids means a non-gear
    # DAT simply yields no match.
    dat = normalize_dat(spec)
    if dat is None:
        raise ValueError(
            f"'{spec}' is not a race name, a DAT path (e.g. ROM/33/17), or a file_id")

    from xi.ftable.xi_core import load_all_tables, scan_file_ids
    if tables is None:
        tables = load_all_tables()
    for entry in scan_file_ids(sorted(index), tables):
        if entry['dat'] == dat:
            race, slot, model_id = index[entry['file_id']]
            return (race, slot, model_id, entry['file_id'])

    raise ValueError(
        f"{dat} is not a registered gear model — no race/slot table references it "
        f"(it may be a monster, zone, or UI DAT)")
