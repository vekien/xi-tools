# ---------------------------------------------------------------------------
# FFXI "look" appearance blob — the 20-byte structure stored per NPC (CatsEyeXI
# `npc_list.look BINARY(20)` = the client/server `look_t`, src/common/mmo.h). It's how
# an event/cutscene NPC's 3D appearance is defined: either a single fixed model, or a
# race + equipment set (the same data a player character carries).
#
#   u16 size            model type (see LOOK_MODELTYPE): 0 = standard, 1 = equipped, …
#   u16 modelid / {u8 face; u8 race}   union — modelid when standard; face+race when equipped
#   u16 slots[8]        head, body, hands, legs, feet, main, sub, ranged (equipped only)
#
# Each equipped slot value packs the slot index in the **top nibble** and the gear
# **model id in the low 12 bits** (e.g. body 0x20AC → body slot, model 0xAC = 172) — the
# low 12 bits are what `resolve_gear_dat(race, slot, model_id)` consumes.
# ---------------------------------------------------------------------------

LOOK_RACE_NAMES = {1: 'HumeMale', 2: 'HumeFemale', 3: 'ElvaanMale', 4: 'ElvaanFemale',
                   5: 'TaruMale', 6: 'TaruFemale', 7: 'Mithra', 8: 'Galka'}
LOOK_SLOTS = ['head', 'body', 'hands', 'legs', 'feet', 'main', 'sub', 'ranged']
LOOK_MODELTYPE = {0: 'standard', 1: 'equipped', 2: 'door', 3: 'elevator',
                  4: 'ship', 6: 'automaton', 7: 'chocobo'}


def parse_look(blob) -> dict:
    """Decode a 20-byte FFXI ``look`` appearance blob (CatsEyeXI ``npc_list.look``).

    Returns ``{"type": ...}``:
      * non-equipped → ``{"type": "standard"|"door"|…, "modelid": int}`` (a single fixed model).
      * equipped character → ``{"type": "equipped", "race": int, "raceName": str|None,
        "face": int, "slots": {slot: model_id}}`` — only worn slots, model_id = low 12 bits.

    Raises ``ValueError`` if the blob isn't 20 bytes."""
    b = bytes(blob)
    if len(b) < 20:
        raise ValueError(f"look blob must be 20 bytes, got {len(b)}")
    size = int.from_bytes(b[0:2], 'little')
    if size != 1:                                   # not an equipped character
        return {"type": LOOK_MODELTYPE.get(size, f"type{size}"),
                "modelid": int.from_bytes(b[2:4], 'little')}
    face, race = b[2], b[3]
    slots = {}
    for i, name in enumerate(LOOK_SLOTS):
        v = int.from_bytes(b[4 + i * 2: 6 + i * 2], 'little')
        if v:                                       # 0 = empty slot
            slots[name] = v & 0x0FFF                # low 12 bits = gear model id
    return {"type": "equipped", "race": race, "raceName": LOOK_RACE_NAMES.get(race),
            "face": face, "slots": slots}
GROUPS_PER_SLOT = 6
BYTES_PER_SLOT  = GROUPS_PER_SLOT * 8   # 6 × (base uint32 + count uint32) = 48
BYTES_PER_TABLE = len(SLOTS) * BYTES_PER_SLOT  # 9 × 48 = 432


def parse_race_table(data) -> dict:
    """Parse 432-byte raw table into {slot: [(base_fid, count), ...]}."""
    result = {}
    offset = 0
    for slot in SLOTS:
        groups = []
        for _ in range(GROUPS_PER_SLOT):
            base_fid = struct.unpack_from('<I', data, offset)[0]
            count    = struct.unpack_from('<I', data, offset + 4)[0]
            offset  += 8
            groups.append((base_fid, count))
        result[slot] = groups
    return result


def slot_file_ids(groups: list) -> list[tuple[int, int]]:
    """
    Expand [(base_fid, count), ...] to [(model_id, file_id), ...].
    model_id is the cumulative index across all groups for this slot.
    Groups with base_fid=0 or count=0 are skipped (zero-pad entries).
    """
    entries = []
    model_id = 0
    for base_fid, count in groups:
        if count == 0:
            continue
        if base_fid == 0:
            model_id += count
            continue
        for i in range(count):
            entries.append((model_id + i, base_fid + i))
        model_id += count
    return entries


